import { existsSync, readFileSync } from "node:fs";
import ts from "typescript";
import { parse } from "yaml";

const modules = [
  ["src/auth/routes/index.ts", ["/api/v1/auth", "/api/auth"]],
  [
    "src/onboarding/routes.ts",
    ["/api/v1/auth/onboarding", "/api/v1/onboarding"],
  ],
  ["src/participants/routes/index.ts", ["/api/v1/participants"]],
  ["src/points/routes/index.ts", ["/api/v1/points"]],
  ["src/parent/routes/index.ts", ["/api/v1/parent"]],
  ["src/child/routes/index.ts", ["/api/v1/child"]],
  ["src/mentor/routes.ts", ["/api/v1/mentor"]],
  ["src/observer/routes.ts", ["/api/v1/observer"]],
  ["src/notifications/routes.ts", ["/api/v1/notifications"]],
  ["src/reports/routes.ts", ["/api/v1/reports"]],
  ["src/administration/routes.ts", ["/api/v1/administration", "/api/v1/admin"]],
  ["src/bible/admin-routes.ts", ["/api/v1/administration", "/api/v1/admin"]],
  ["src/configuration/routes.ts", ["/api/v1/configuration"]],
];
const verbs = new Set(["get", "post", "put", "patch", "delete"]);
const join = (prefix, path) => `${prefix}${path === "/" ? "" : path}`;
const openApiPath = (path) => path.replace(/:([A-Za-z0-9_]+)/g, "{$1}");

export function operationsIn(file, prefixes) {
  const source = ts.createSourceFile(
    file,
    readFileSync(file, "utf8"),
    ts.ScriptTarget.Latest,
    true,
  );
  const operations = [];
  const visit = (node) => {
    if (
      ts.isCallExpression(node) &&
      ts.isPropertyAccessExpression(node.expression) &&
      verbs.has(node.expression.name.text) &&
      node.arguments[0] &&
      (ts.isStringLiteral(node.arguments[0]) ||
        ts.isArrayLiteralExpression(node.arguments[0]))
    ) {
      const paths = ts.isStringLiteral(node.arguments[0])
        ? [node.arguments[0].text]
        : node.arguments[0].elements
            .filter(ts.isStringLiteral)
            .map((element) => element.text);
      for (const prefix of prefixes) {
        for (const path of paths)
          operations.push({
            method: node.expression.name.text.toUpperCase(),
            path: join(prefix, path),
            source: file,
          });
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  return operations;
}

const mounted = modules.flatMap(([file, prefixes]) =>
  operationsIn(file, prefixes),
);
// These registrations are generated by a lifecycle loop in administration/routes.ts.
for (const prefix of ["/api/v1/administration", "/api/v1/admin"])
  for (const transition of ["activate", "close", "archive"])
    mounted.push({
      method: "POST",
      path: `${prefix}/quarters/:quarterId/${transition}`,
      source: "src/administration/routes.ts (generated)",
    });
// Source completion routes are generated from the source registry in points/routes/index.ts.
for (const source of [
  "daily-check-ins",
  "gratitude",
  "character-assessments",
  "bible-activities",
  "family-activities",
  "reading",
  "project-milestones",
  "project-completions",
  "academic-sessions",
  "observation-bonuses",
])
  mounted.push({
    method: "POST",
    path: `/api/v1/points/sources/${source}/completions`,
    source: "src/points/routes/index.ts (generated)",
  });
mounted.push(
  { method: "HEAD", path: "/", source: "src/app.ts" },
  { method: "GET", path: "/", source: "src/app.ts" },
  { method: "GET", path: "/health", source: "src/app.ts" },
  { method: "GET", path: "/api/v1/health", source: "src/app.ts" },
);
mounted.sort(
  (a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method),
);

const spec = parse(readFileSync("openapi.yaml", "utf8"));
const published = new Set();
for (const [path, item] of Object.entries(spec.paths ?? {})) {
  for (const method of verbs)
    if (item[method]) published.add(`${method.toUpperCase()} /api/v1${path}`);
}
const canonical = mounted.filter(({ path }) => path.startsWith("/api/v1/"));
const templateMatches = (template, concrete) => {
  const escaped = template
    .split("/")
    .map((segment) =>
      /^\{[A-Za-z0-9_]+\}$/.test(segment)
        ? "[^/]+"
        : segment.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"),
    )
    .join("/");
  return new RegExp(`^${escaped}$`).test(concrete);
};
const undocumented = canonical.filter(
  ({ method, path }) =>
    ![...published].some((operation) => {
      const separator = operation.indexOf(" ");
      return (
        operation.slice(0, separator) === method &&
        templateMatches(operation.slice(separator + 1), openApiPath(path))
      );
    }),
);
const unmounted = [...published].filter((operation) => {
  const separator = operation.indexOf(" ");
  return !canonical.some(
    ({ method, path }) =>
      method === operation.slice(0, separator) &&
      templateMatches(operation.slice(separator + 1), openApiPath(path)),
  );
});

const frontendPath = process.env.FRONTEND_OPENAPI_PATH;
let frontend = {
  status: "blocked",
  reason: "FRONTEND_OPENAPI_PATH was not supplied",
};
if (frontendPath && existsSync(frontendPath)) {
  const frontendSpec = parse(readFileSync(frontendPath, "utf8"));
  const operations = new Set();
  for (const [path, item] of Object.entries(frontendSpec.paths ?? {}))
    for (const method of verbs)
      if (item[method])
        operations.add(`${method.toUpperCase()} /api/v1${path}`);
  frontend = {
    status: "compared",
    missingFromBackend: [...operations].filter(
      (operation) => !published.has(operation),
    ),
    missingFromFrontend: [...published].filter(
      (operation) => !operations.has(operation),
    ),
  };
} else if (frontendPath) {
  frontend.reason = `Frontend contract does not exist: ${frontendPath}`;
}

const result = {
  generatedAt: new Date().toISOString(),
  mountedCount: mounted.length,
  publishedCount: published.size,
  mounted,
  undocumented,
  unmounted,
  frontend,
  releaseGate:
    undocumented.length === 0 &&
    unmounted.length === 0 &&
    frontend.status === "compared" &&
    frontend.missingFromBackend.length === 0
      ? "pass"
      : "fail",
};
console.log(JSON.stringify(result, null, 2));
if (result.releaseGate !== "pass") process.exitCode = 1;
